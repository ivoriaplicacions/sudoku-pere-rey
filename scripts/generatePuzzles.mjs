/**
 * Offline Sudoku puzzle generator.
 *
 * Produces src/data/puzzles.ts: 40 levels × 20 puzzles = 800, following the
 * ladder in src/data/ladder.ts. Every puzzle demands exactly the technique of
 * its level as its hardest step, never needs a guess and has one solution.
 *
 * Inside each step of the ladder the puzzles go from gentler to tougher, so the
 * climb continues from one level to the next and inside each level too.
 *
 * Run with: node scripts/generatePuzzles.mjs   (several minutes)
 * Needs Node 22.18 or later, which imports TypeScript files directly.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LADDER, LEVEL_COUNT, PUZZLES_PER_LEVEL } from '../src/data/ladder.ts';
import { difficultyScore, generateForTechnique } from './lib/targetedGenerator.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT_FILE = resolve(HERE, '../src/data/puzzles.ts');

/** The rarest technique turns up about once in 300 grids; this is far beyond that. */
const MAX_ATTEMPTS = 50_000;

const started = Date.now();
const all = [];
const stats = [];
const seen = new Set();

LADDER.forEach((step, stepIndex) => {
  const stepStarted = Date.now();
  const needed = (step.to - step.from + 1) * PUZZLES_PER_LEVEL;
  const made = [];

  // Seeds are spaced out so a retry after a duplicate never meets the next puzzle's.
  for (let seed = stepIndex * 100_000 + 1; made.length < needed; seed++) {
    const puzzle = generateForTechnique(step.technique, seed, {
      minPerUnit: step.minPerUnit,
      targetGivens: step.givens ?? 0,
      maxAttempts: MAX_ATTEMPTS,
    });
    if (!puzzle) {
      throw new Error(`Levels ${step.from}–${step.to}: no ${step.technique} puzzle in ${MAX_ATTEMPTS} grids`);
    }
    if (seen.has(puzzle.puzzle)) continue;
    seen.add(puzzle.puzzle);
    made.push(puzzle);
  }

  // Stable sort: equal scores keep the order they were generated in.
  made.sort((a, b) => difficultyScore(a) - difficultyScore(b));

  made.forEach((puzzle, index) => {
    all.push({
      ...puzzle,
      level: step.from + Math.floor(index / PUZZLES_PER_LEVEL),
      puzzleNumber: (index % PUZZLES_PER_LEVEL) + 1,
    });
  });

  for (let level = step.from; level <= step.to; level++) {
    const inLevel = all.filter((puzzle) => puzzle.level === level);
    const givens = inLevel.map((puzzle) => puzzle.givens);
    const hard = inLevel.map((puzzle) => puzzle.hardestSteps);
    stats.push({
      level,
      technique: step.technique,
      givens: `${Math.min(...givens)}–${Math.max(...givens)}`,
      'hard steps': `${Math.min(...hard)}–${Math.max(...hard)}`,
    });
  }
  const seconds = ((Date.now() - stepStarted) / 1000).toFixed(1);
  console.log(`… levels ${step.from}–${step.to} (${step.technique}): ${needed} puzzles in ${seconds}s`);
});

if (all.length !== LEVEL_COUNT * PUZZLES_PER_LEVEL) {
  throw new Error(`Expected ${LEVEL_COUNT * PUZZLES_PER_LEVEL} puzzles, made ${all.length}`);
}

const lines = all
  .map((p) => `  '${p.level}|${p.puzzleNumber}|${p.givens}|${p.puzzle}|${p.solution}',`)
  .join('\n');

const file = `// AUTO-GENERATED by scripts/generatePuzzles.mjs — do not edit by hand.
// Each entry is "level|puzzleNumber|givenCount|puzzle|solution", where the two
// grids are 81 digits read row by row and 0 marks an empty cell.
// ${LEVEL_COUNT} levels × ${PUZZLES_PER_LEVEL} = ${all.length} puzzles, following src/data/ladder.ts.
// Every puzzle has exactly one solution and demands the technique of its level
// as its hardest step. Inside a ladder step they go from gentler to tougher.

export const PACKED_PUZZLES: readonly string[] = [
${lines}
];
`;

mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(OUT_FILE, file, 'utf8');

console.log(`Generated ${all.length} puzzles in ${((Date.now() - started) / 1000).toFixed(1)}s`);
console.table(stats);
console.log(`Written to ${OUT_FILE}`);
